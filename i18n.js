let lang = 'zh';
export const getLang = () => lang;
export function setLang(id) {
  lang = STR[id] ? id : 'zh';
  document.documentElement.lang = LANGS.find(l => l.id === lang).html;
}
export function detectLang() {
  const n = (navigator.language || 'zh').toLowerCase();
  return n.startsWith('zh') ? 'zh' : n.startsWith('ja') ? 'ja' : n.startsWith('ko') ? 'ko' : 'en';
}
export function t(key, ...args) {
  const v = STR[lang][key] ?? STR.zh[key];
  return typeof v === 'function' ? v(...args) : v;
}
// fills every [data-i18n] element's text
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
